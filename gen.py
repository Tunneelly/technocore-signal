import os
os.makedirs('/workspaces/technocore-signal', exist_ok=True)
content = []
content.append('import express from "express";')
content.append('import fetch from "node-fetch";')
content.append('import nacl from "tweetnacl";')
content.append('')
content.append('const PORT = process.env.PORT || 3000;')
content.append('const ROOM = process.env.ROOM || "technocore";')
content.append('const LIVE_API = process.env.LIVE_API || "https://technocore.chat";')
content.append('')
content.append('function abbreviateDid(did) {')
content.append('  const prefix = "did:key:";')
content.append('  const body = did.slice(prefix.length);')
content.append('  if (body.length <= 8) return did;')
content.append('  return prefix + body.substring(0, 4) + "…" + body.substring(body.length - 4);')
content.append('}')
content.append('')
content.append('function verifyEd25519(did, signature, message) {')
content.append('  const didPrefix = "did:key:";')
content.append('  if (!did.startsWith(didPrefix)) {')
content.append('    return { valid: false, reason: "invalid_did_format" };')
content.append('  }')
content.append('  const b58id = did.slice(didPrefix.length);')
content.append('  if (b58id.length !== 48) {')
content.append('    return { valid: false, reason: "invalid_did_length", got: b58id.length };')
content.append('  }')
content.append('  if (!b58id.startsWith("z6M")) {')
content.append('    return { valid: false, reason: "invalid_did_prefix" };')
content.append('  }')
content.append('  const _B58 = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz";')
content.append('  const _B58_INDEX = {};')
content.append('  for (let i = 0; i < _B58.length; i++) _B58_INDEX[_B58[i]] = i;')
content.append('  let n = 0;')
content.append('  for (let i = 0; i < b58id.length; i++) {')
content.append('    const ch = b58id[i];')
content.append('    if (!_B58_INDEX[ch]) return { valid: false, reason: "invalid_did_base58" };')
content.append('    n = n * 58 + _B58_INDEX[ch];')
content.append('  }')
content.append('  const leading = b58id.length - b58id.replace(/^1/, "").length;')
content.append('  let payload = n.toString(16).padStart(64, "0");')
content.append('  if (payload.length < 64) payload = "0".repeat(64 - payload.length) + payload;')
content.append('  const keyBytes = Buffer.from(payload, "hex");')
content.append('  if (keyBytes.length !== 32) {')
content.append('    return { valid: false, reason: "invalid_key_length" };')
content.append('  }')
content.append('  const verifyKey = nacl.sign.key.fromPublic(keyBytes);')
content.append('  const SIG_CHARS = 86;')
content.append('  if (typeof signature !== "string" || signature.length !== SIG_CHARS) {')
content.append('    return { valid: false, reason: "bad_signature_length" };')
content.append('  }')
content.append('  const lastChar = signature.charAt(SIG_CHARS - 1);')
content.append('  if (!"AQgw".includes(lastChar)) {')
content.append('    return { valid: false, reason: "non_canonical_sig" };')
content.append('  }')
content.append('  let b64 = signature.substring(0, SIG_CHARS);')
content.append('  b64 = b64.replace(/[^a-zA-Z0-9_-]/g, "");')
content.append('  while (b64.length % 4 !== 0) b64 += "=";')
content.append('  const sigBytes = Buffer.from(b64, "base64");')
content.append('  if (sigBytes.length !== 64) {')
content.append('    return { valid: false, reason: "bad_sig_bytes_length" };')
content.append('  }')
content.append('  const swept = sweepText(message);')
content.append('  const canonical = ROOM + "|" + nonce + "|" + swept;')
content.append('  try {')
content.append('    const isValid = nacl.sign.det.verify(')
content.append('      Buffer.from(canonical, "utf-8"),')
content.append('      sigBytes,')
content.append('      verifyKey')
content.append('    );')
content.append('    if (isValid) {')
content.append('      return { valid: true, canonical };')
content.append('    } else {')
content.append('      return { valid: false, reason: "signature_mismatch" };')
content.append('    }')
content.append('  } catch (e) {')
content.append('    return { valid: false, reason: "verification_error" };')
content.append('  }')
content.append('}')
content.append('')
content.append('function sweepText(text) {')
content.append('  if (typeof text !== "string") return String(text);')
content.append('  const swept = text.replace(/\\p{Cc}|\\p{Cf}|\\p{Cs}|\\p{Co}|\\p{Zl}|\\p{Zp}/gu, " ");')
content.append('  return swept.trim();')
content.append('}')
content.append('')
content.append('function fetchMessages(sinceSeq = null) {')
content.append('  return new Promise((resolve, reject) => {')
content.append('    const url = LIVE_API + "/r/" + ROOM + "?format=json&limit=50" + (sinceSeq !== null ? "&since=" + sinceSeq : "");')
content.append('    fetch(url)')
content.append('      .then((res) => {')
content.append('        if (!res.ok) throw new Error("API responded " + res.status);')
content.append('        return res.json();')
content.append('      })')
content.append('      .then((data) => {')
content.append('        const verifiedMessages = data.messages.map((msg) => {')
content.append('          const result = verifyEd25519(msg.from, msg.sig, msg.text);')
content.append('          return {')
content.append('            seq: msg.seq,')
content.append('            ts: msg.ts,')
content.append('            did: msg.from,')
content.append('            didAbbreviated: abbreviateDid(msg.from),')
content.append('            text: msg.text,')
content.append('            nonce: msg.nonce,')
content.append('            signature: msg.sig,')
content.append('            signatureValid: result.valid,')
content.append('            signatureReason: result.valid ? undefined : (result.reason || "unverifiable"),')
content.append('            canonical: result.canonical || null,')
content.append('            sourceUrl: LIVE_API + "/r/" + ROOM + "?seq=" + msg.seq')
content.append('          };')
content.append('        });')
content.append('        resolve({')
content.append('          room: data.room,')
content.append('          count: data.count,')
content.append('          first_seq: data.first_seq,')
content.append('          last_seq: data.last_seq,')
content.append('          generation: data.generation,')
content.append('          messages: verifiedMessages')
content.append('        });')
content.append('      })')
content.append('      .catch((err) => reject(err));')
content.append('  });')
content.append('}')
content.append('')
content.append('function computeOpenQuestions(messages) {')
content.append('  const questionMessages = [];')
content.append('  for (let i = 0; i < messages.length; i++) {')
content.append('    const msg = messages[i];')
content.append('    if (msg.text.includes("?") && msg.signatureValid) {')
content.append('      const laterReplies = messages.slice(i + 1).filter(')
content.append('        later => later.did !== msg.did && later.signatureValid')
content.append('      );')
content.append('      if (laterReplies.length === 0) {')
content.append('        questionMessages.push({')
content.append('          seq: msg.seq,')
content.append('          did: msg.did,')
content.append('          didAbbreviated: msg.didAbbreviated,')
content.append('          text: msg.text,')
content.append('          ts: msg.ts')
content.append('        });')
content.append('      }')
content.append('    }')
content.append('  }')
content.append('  return questionMessages;')
content.append('}')
content.append('')
content.append('const app = express();')
content.append('')
content.append('app.get("/api/health", (req, res) => {')
content.append('  res.json({')
content.append('    status: "ok",')
content.append('    room: ROOM,')
content.append('    timestamp: new Date().toISOString()')
content.append('  });')
content.append('})')
content.append('')
content.append('app.get("/api/messages", async (req, res) => {')
content.append('  try {')
content.append('    const sinceSeq = req.query.since ? parseInt(req.query.since, 10) : null;')
content.append('    const data = await fetchMessages(sinceSeq);')
content.append('    if (!data) {')
content.append('      return res.status(500).json({')
content.append('        error: "failed_to_fetch",')
content.append('        message: "Could not fetch messages from the API. Is the live mode available?"')
content.append('      });')
content.append('    }')
content.append('    res.json(data);')
content.append('  } catch (error) {')
content.append('    console.error("Error in /api/messages:", error);')
content.append('    res.status(500).json({')
content.append('      error: "internal_error",')
content.append('      message: error.message')
content.append('    });')
content.append('  }')
content.append('})')
content.append('')
content.append('app.get("/api/open-questions", async (req, res) => {')
content.append('  try {')
content.append('    const sinceSeq = req.query.since ? parseInt(req.query.since, 10) : null;')
content.append('    const messagesData = await fetchMessages(sinceSeq);')
content.append('    if (!messagesData) {')
content.append('      return res.status(500).json({')
content.append('        error: "failed_to_fetch",')
content.append('        message: "Could not fetch messages from the API."')
content.append('      });')
content.append('    }')
content.append('    const openQuestions = computeOpenQuestions(messagesData.messages);')
content.append('    res.json({')
content.append('      room: messagesData.room,')
content.append('      total_messages: messagesData.messages.length,')
content.append('      open_questions: openQuestions.length,')
content.append('      questions: openQuestions')
content.append('    });')
content.append('  } catch (error) {')
content.append('    console.error("Error in /api/open-questions:", error);')
content.append('    res.status(500).json({')
content.append('      error: "internal_error",')
content.append('      message: error.message')
content.append('    });')
content.append('  }')
content.append('})')
content.append('')
content.append('app.listen(PORT, () => {')
content.append('  console.log("Technocore Signal backend running on http://localhost:" + PORT);')
content.append('  console.log("Room: " + ROOM);')
content.append('  console.log("Live API: " + LIVE_API);')
content.append('})')
with open('/workspaces/technocore-signal/index.js', 'w', encoding='utf-8') as f:
    f.write('\n'.join(content))
print('Done')
